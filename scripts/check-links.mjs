// Checks every external link in the site's source and writes docs/link-test-record.md.
// Usage: npm run check:links
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOTS = ["data", "app", "content", "components", "lib"];
const URL_RE = /https?:\/\/[^\s"'`<>)\]}]+/g;
const IGNORE = [/^https?:\/\/localhost/];

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : /\.(tsx?|mdx?)$/.test(p) ? [p] : [];
  });
}

const found = new Map(); // url -> Set(files)
for (const file of ROOTS.flatMap(walk)) {
  for (const m of readFileSync(file, "utf8").matchAll(URL_RE)) {
    const url = m[0].replace(/[.,;:]+$/, "");
    if (IGNORE.some((r) => r.test(url))) continue;
    if (!found.has(url)) found.set(url, new Set());
    found.get(url).add(file);
  }
}

const UA = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130 Safari/537.36 STOIC-link-check";

async function check(url) {
  for (const method of ["HEAD", "GET"]) {
    try {
      const res = await fetch(url, {
        method,
        redirect: "follow",
        headers: { "user-agent": UA, accept: "text/html,*/*" },
        signal: AbortSignal.timeout(20000),
      });
      if (method === "HEAD" && !res.ok) continue; // some servers mis-handle HEAD; retry with GET
      return { status: res.status, ok: res.ok, finalUrl: res.url };
    } catch (e) {
      if (method === "GET") return { status: "error", ok: false, finalUrl: "", error: e.cause?.code ?? e.name };
    }
  }
}

const urls = [...found.keys()].sort();
const results = [];
for (const url of urls) {
  const r = await check(url);
  results.push({ url, ...r });
  console.log(`${r.ok ? "OK  " : "FAIL"} ${r.status} ${url}`);
}

const now = new Date();
const failed = results.filter((r) => !r.ok);
const md = `# Link test record

Automated check of every external link in the site source.
Generated by \`npm run check:links\` (scripts/check-links.mjs).

- Run at: ${now.toISOString()}
- Links checked: ${results.length}
- OK (2xx after redirects): ${results.length - failed.length}
- Need attention: ${failed.length}

A failure here is not always a broken link. Some sites block automated requests, for example with a 403. Open each failing link in a normal browser and record the result in the manual column.

| Result | Status | Link | Ends up at | Manual check (browser) |
|---|---|---|---|---|
${results
  .map(
    (r) =>
      `| ${r.ok ? "OK" : "**CHECK**"} | ${r.status}${r.error ? ` (${r.error})` : ""} | ${r.url} | ${r.finalUrl && r.finalUrl !== r.url ? r.finalUrl : "same"} | ${r.ok ? "n/a" : "[ADD RESULT + DATE]"} |`,
  )
  .join("\n")}
`;
writeFileSync("docs/link-test-record.md", md);
console.log(`\nWrote docs/link-test-record.md (${failed.length} need attention)`);
